"""Regenerate spec/merkle_vectors.txt from the Python implementation.

The vectors pin the Merkle format (RFC 6962 domain tags, odd node promoted) as data, so
the Python package and the Rust core are each checked against the same published contract
on every test run, with no dependency on the optional native extension.
Line formats (fields separated by one space; '-' means empty):
  leaf  <input> <tagged>
  node  <left> <right> <parent>
  root  <leaves,comma-separated> <root>
  proof <leaves,comma-separated> <index> <L|R:hash;...>
"""

import hashlib
from pathlib import Path

from aetherproof.core.hash import compute_merkle_root, merkle_leaf, merkle_node
from aetherproof.core.session import inclusion_proof

OUT = Path(__file__).with_name("merkle_vectors.txt")


def h(i: int) -> str:
    return hashlib.sha256(f"aetherproof-vector-{i}".encode()).hexdigest()


def main() -> None:
    lines = ["# AetherProof Merkle vectors v1. Generated by spec/gen_merkle_vectors.py; do not edit by hand."]
    for i in range(3):
        lines.append(f"leaf {h(i)} {merkle_leaf(h(i))}")
    lines.append(f"node {h(0)} {h(1)} {merkle_node(h(0), h(1))}")
    lines.append(f"root - -")
    for n in (1, 2, 3, 4, 5, 7, 8, 9, 16, 17):
        leaves = [h(i) for i in range(n)]
        lines.append(f"root {','.join(leaves)} {compute_merkle_root(leaves)}")
        for idx in sorted({0, n // 2, n - 1}):
            proof = ";".join(f"{s}:{x}" for s, x in inclusion_proof(leaves, idx)) or "-"
            lines.append(f"proof {','.join(leaves)} {idx} {proof}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(lines) - 1} vectors)")


if __name__ == "__main__":
    main()
